#!/usr/bin/env bash
# Regenerates THIRD_PARTY_LICENSES: the licences of everything built into trimcraft.exe and the
# UI. Run after dependency changes; needs cargo-about (cargo install cargo-about --locked
# --features cli) and node_modules (npm ci).
set -euo pipefail
cd "$(dirname "$0")/.."

ABOUT="${CARGO_ABOUT:-cargo-about}"
OUT=THIRD_PARTY_LICENSES

{
  echo "Third-party licences for Trimcraft"
  echo
  echo "Trimcraft itself is licensed under the GNU General Public License v3.0 or later (LICENSE)."
  echo "It contains the following third-party software, each under the licence shown."
  echo "Generated by scripts/third-party-licenses.sh; do not edit by hand."
} > "$OUT"
"$ABOUT" generate --locked -c scripts/third-party/about.toml scripts/third-party/about.hbs >> "$OUT"
node scripts/third-party/extra.mjs "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
